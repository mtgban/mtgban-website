CREATE TEMP TABLE alt_twins ON COMMIT DROP AS
SELECT a.ban_id AS old_ban_id, t.ban_id AS new_ban_id
  FROM public.variants a
  JOIN public.variants t
    ON t.mtgjson_uuid = a.mtgjson_uuid
   AND t.is_foil = a.is_foil
   AND t.is_etched = a.is_etched
   AND t.language = a.language
   AND NOT t.is_alt
 WHERE a.is_alt AND a.mtgjson_uuid IS NOT NULL
   AND a.mtgjson_uuid NOT IN (SELECT mtgjson_uuid FROM alt_copy_originals);

INSERT INTO public.prices (ban_id, date, provider, price)
SELECT tw.new_ban_id, p.date, p.provider, p.price
  FROM public.prices p
  JOIN alt_twins tw ON p.ban_id = tw.old_ban_id
ON CONFLICT (ban_id, date, provider) DO NOTHING;

DELETE FROM public.prices p USING alt_twins tw WHERE p.ban_id = tw.old_ban_id;
DELETE FROM public.variants v USING alt_twins tw WHERE v.ban_id = tw.old_ban_id;

UPDATE public.variants SET is_alt = false
 WHERE is_alt AND mtgjson_uuid IS NOT NULL
   AND mtgjson_uuid NOT IN (SELECT mtgjson_uuid FROM alt_copy_originals);

-- Only the copies' variants are left flagged
SELECT count(*) AS still_alt FROM public.variants WHERE is_alt;

COMMIT;
